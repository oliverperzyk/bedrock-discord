/**
 * @summary StickerType.
 * @description Numeric values used by Discord sticker resources.
 */
enum StickerType {
    /**
     * @summary STANDARD sticker.
     * @description An official sticker belonging to a pack.
     */
    STANDARD = 1,
    /**
     * @summary GUILD sticker.
     * @description A custom sticker uploaded to a guild.
     */
    GUILD = 2,
}

export { StickerType }
