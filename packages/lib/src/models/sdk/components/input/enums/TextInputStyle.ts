/**
 * @summary Text input style.
 * @description Single-line or multi-line appearance for a modal text input.
 */
enum TextInputStyle {
    /**
     * @summary Short input.
     * @description Single-line text field.
     */
    SHORT = 1,
    /**
     * @summary Paragraph input.
     * @description Multi-line text field.
     */
    PARAGRAPH = 2,
}

export { TextInputStyle }
